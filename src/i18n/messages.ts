export const LOCALES = {
  en, de, es, fr, ja, ko, nl, pl, 'pt-BR': ptBR, tr, uk, 'zh-CN': zhCN, 'zh-TW': zhTW,
} satisfies Record<string, Messages>;

export type Locale = keyof typeof LOCALES;

const isLocale = (value: string): value is Locale => Object.hasOwn(LOCALES, value);

/** Exact tag first (`pt-BR`), then the language (`de-AT` → `de`, `zh-HK` → `zh-TW`), then English. */
export const resolveLocale = (tag: string): Locale => {
  if (isLocale(tag)) return tag;
  const lower = tag.toLowerCase();
  const exact = Object.keys(LOCALES).find((key) => key.toLowerCase() === lower);
  if (exact && isLocale(exact)) return exact;
  const language = lower.split(/[-_]/)[0] ?? '';
  if (language === 'zh') return /(tw|hk|mo|hant)/.test(lower) ? 'zh-TW' : 'zh-CN';
  if (language === 'pt') return 'pt-BR';
  return isLocale(language) ? language : 'en';
};

export const messagesFor = (tag: string): Messages => LOCALES[resolveLocale(tag)];

export const format = (template: string, values: Record<string, string | number>): string =>
  template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));
